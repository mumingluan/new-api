import { toIntlLocale } from '@/i18n/languages'

export async function copyText(text: string): Promise<void> {
  if (navigator.clipboard?.writeText) {
    await navigator.clipboard.writeText(text)
    return
  }

  const textarea = document.createElement('textarea')
  textarea.value = text
  textarea.style.position = 'fixed'
  textarea.style.opacity = '0'
  document.body.appendChild(textarea)
  textarea.select()
  document.execCommand('copy')
  textarea.remove()
}

export function formatTimestamp(timestamp: number, locale: string): string {
  return new Date(timestamp * 1000).toLocaleString(toIntlLocale(locale))
}

export function getUsageDateRange(days = 100): {
  startDate: string
  endDate: string
} {
  const end = new Date()
  const start = new Date(end)
  start.setDate(start.getDate() - days)

  const format = (date: Date) => {
    const year = date.getFullYear()
    const month = String(date.getMonth() + 1).padStart(2, '0')
    const day = String(date.getDate()).padStart(2, '0')
    return `${year}-${month}-${day}`
  }

  return { startDate: format(start), endDate: format(end) }
}

export function formatQuota(quota: number): string {
  return (quota / 500_000).toFixed(6)
}
